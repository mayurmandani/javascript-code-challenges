/*  slice() method is a built-in function used to extract a portion of an array or a string and return it as a new object. slice() is a non-destructive operation, meaning it does not change the original array or string */

const arr = [1, 2, 3, 4];

console.log(arr.slice(1, 3));  // [ 2, 3 ]

console.log(arr); // [ 1, 2, 3, 4 ]
